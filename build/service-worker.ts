// Vite plugin: after a build, writes dist/sw.js, a service worker that keeps
// a copy of every built file so the game runs offline (as a Home Screen app).
//
// The service worker's version is a hash of all the built files, so any change
// to the game changes sw.js, and the browser notices there is an update. A new
// version waits until the page asks it to take over (see src/ui/updates.ts),
// so a race is never interrupted.

import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import type { Plugin, ResolvedConfig } from 'vite';

export const SERVICE_WORKER = 'sw.js';

/** Every file under `dir`, as relative URL paths, sorted, excluding the service worker. */
export function listFiles(dir: string): string[] {
  const out: string[] = [];
  const walk = (d: string) => {
    for (const name of readdirSync(d)) {
      const path = join(d, name);
      if (statSync(path).isDirectory()) walk(path);
      else out.push(relative(dir, path).split(sep).join('/'));
    }
  };
  walk(dir);
  return out.filter((f) => f !== SERVICE_WORKER).sort();
}

/** A short hash of the files' names and contents: changes whenever any file does. */
export function versionOf(dir: string, files: string[]): string {
  const hash = createHash('sha256');
  for (const file of files) {
    hash.update(file);
    hash.update('\0');
    hash.update(readFileSync(join(dir, file)));
  }
  return hash.digest('hex').slice(0, 12);
}

/** The service worker's source, precaching `files` under cache `version`. */
export function serviceWorkerSource(files: string[], version: string): string {
  // index.html is cached as "./", the address the game is opened at.
  const urls = ['./', ...files.filter((f) => f !== 'index.html').map((f) => `./${f}`)];
  return `// Generated by build/service-worker.ts. Do not edit.
const VERSION = ${JSON.stringify(version)};
const CACHE = 'circus-maximus-' + VERSION;
const FILES = ${JSON.stringify(urls, null, 2)};

self.addEventListener('install', (event) => {
  // Fetch everything before this version can take over, bypassing the HTTP
  // cache so a stale copy is never stored.
  event.waitUntil(
    caches.open(CACHE).then((cache) =>
      cache.addAll(FILES.map((url) => new Request(url, { cache: 'reload' }))),
    ),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys.filter((k) => k.startsWith('circus-maximus-') && k !== CACHE).map((k) => caches.delete(k)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'SKIP_WAITING') self.skipWaiting();
  if (event.data && event.data.type === 'VERSION') event.source.postMessage({ type: 'VERSION', version: VERSION });
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;
  // Opening the game, with any settings in the query string, gets the cached
  // page. Vary is ignored: scripts load as CORS requests (with an Origin
  // header) but were cached without one, and some servers send Vary: Origin.
  const lookup = request.mode === 'navigate' ? './' : request;
  event.respondWith(
    caches
      .open(CACHE)
      .then((cache) =>
        cache.match(lookup, { ignoreSearch: request.mode === 'navigate', ignoreVary: true }),
      )
      .then((cached) => cached || fetch(request)),
  );
});
`;
}

export function serviceWorker(): Plugin {
  let config: ResolvedConfig;
  return {
    name: 'chariot-service-worker',
    apply: 'build',
    configResolved(resolved) {
      config = resolved;
    },
    closeBundle() {
      const dir = join(config.root, config.build.outDir);
      const files = listFiles(dir);
      const version = versionOf(dir, files);
      writeFileSync(join(dir, SERVICE_WORKER), serviceWorkerSource(files, version));
      this.info(`service worker ${version}: ${files.length} files for offline use`);
    },
  };
}
